import {
  AvailabilityAtom,
  FailureEventAtom,
  LogicExpression,
  TraceabilityRecord
} from './ft-generation.models';
import { KnowledgeBaseProvider } from './knowledge-base.contract';

export interface FailureLogicResult {
  expression: LogicExpression;
  traceability: readonly TraceabilityRecord[];
  warnings: readonly string[];
}

export function buildFailureLogic(
  success: LogicExpression,
  knowledgeBase: KnowledgeBaseProvider
): FailureLogicResult {
  const traceability: TraceabilityRecord[] = [];
  const warnings: string[] = [];

  const eventExpression = (atom: AvailabilityAtom): LogicExpression => {
    if (atom.kind === 'COMPONENT_AVAILABLE') {
      const definition = knowledgeBase.getClass(atom.kbClass);
      if (!definition || definition.failureModes.length === 0) {
        warnings.push(`No KB failure modes defined for ${atom.kbClass} (${atom.modelNodeId}).`);
        const fallback: FailureEventAtom = {
          kind: 'FAILURE_EVENT',
          eventId: `${atom.modelNodeId}-UNAVAILABLE`,
          category: 'BASIC_EVENT',
          description: `${atom.modelNodeId} unavailable`,
          modelNodeId: atom.modelNodeId,
          kbClass: atom.kbClass,
          kbFailureMode: 'UNSPECIFIED'
        };
        traceability.push({
          generatedRecordId: fallback.eventId,
          modelNodeId: atom.modelNodeId,
          kbClass: atom.kbClass,
          kbFailureMode: 'UNSPECIFIED',
          reason: 'Fallback component-unavailability event because no KB failure mode was available.'
        });
        return { kind: 'FAILURE_EVENT', atom: fallback };
      }

      const events: LogicExpression[] = definition.failureModes.map(mode => {
        const eventId = `${atom.modelNodeId}-${mode.basicEventSuffix}`;
        traceability.push({
          generatedRecordId: eventId,
          modelNodeId: atom.modelNodeId,
          kbClass: atom.kbClass,
          kbFailureMode: mode.code,
          reason: `Generated from KB failure mode ${mode.code} while negating component availability.`
        });
        return {
          kind: 'FAILURE_EVENT',
          atom: {
            kind: 'FAILURE_EVENT',
            eventId,
            category: 'BASIC_EVENT',
            description: mode.description,
            modelNodeId: atom.modelNodeId,
            kbClass: atom.kbClass,
            kbFailureMode: mode.code
          }
        };
      });

      return events.length === 1 ? events[0] : { kind: 'OR', children: events };
    }

    const category =
      atom.kind === 'FLAG_ACTIVE'
        ? 'HOUSE_EVENT'
        : atom.kind === 'BOUNDARY_AVAILABLE'
          ? 'TRANSFER'
          : 'BASIC_EVENT';

    const suffix =
      atom.kind === 'FLAG_ACTIVE'
        ? 'NOT-ACTIVE'
        : atom.kind === 'BOUNDARY_AVAILABLE'
          ? 'BOUNDARY-UNAVAILABLE'
          : 'SOURCE-UNAVAILABLE';

    const eventId = `${atom.modelNodeId}-${suffix}`;
    traceability.push({
      generatedRecordId: eventId,
      modelNodeId: atom.modelNodeId,
      kbClass: atom.kbClass,
      reason: `Generated by negating ${atom.kind}.`
    });

    return {
      kind: 'FAILURE_EVENT',
      atom: {
        kind: 'FAILURE_EVENT',
        eventId,
        category,
        description: `Failure of requirement: ${atom.description}`,
        modelNodeId: atom.modelNodeId,
        kbClass: atom.kbClass
      }
    };
  };

  const negate = (expr: LogicExpression): LogicExpression => {
    switch (expr.kind) {
      case 'TRUE':
        return { kind: 'FALSE' };
      case 'FALSE':
        return { kind: 'TRUE' };
      case 'AVAILABILITY':
        return eventExpression(expr.atom);
      case 'FAILURE_EVENT':
        return expr;
      case 'AND':
        return { kind: 'OR', children: expr.children.map(negate) };
      case 'OR':
        return { kind: 'AND', children: expr.children.map(negate) };
    }
  };

  return {
    expression: negate(success),
    traceability,
    warnings
  };
}
